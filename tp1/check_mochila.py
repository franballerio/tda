def resolver_mochila_v2(capacidad: int, peso: list[int], valor: list[int]) -> int:
    dp = [0] * (capacidad + 1)
    for i in range(len(peso)):
        for w in range(capacidad, peso[i] - 1, -1):
            dp[w] = max(dp[w], dp[w - peso[i]] + valor[i])
    return dp[capacidad]

